import { test, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';

test('daily mood faces save per crew and support all slider steps and cancellation', async ({ page, request }) => {
  const api = 'http://127.0.0.1:18000/api/v1';
  const current = await (await request.get(`${api}/demo/control`)).json();
  await request.post(`${api}/demo/control`, { data: { action: 'RESTART', expected_revision: current.revision, astronaut_id: 'DEMO-CREW-001' } });
  await page.goto('/');
  const mood = page.getByRole('button', { name: /^Mood for Alex Morgan:/ });
  await expect(mood).toBeEnabled();
  const title = await page.getByRole('heading', { name: 'Mission dashboard', exact: true }).boundingBox();
  const face = await mood.boundingBox();
  const status = await page.locator('.page-heading .status').boundingBox();
  expect(face!.x).toBeGreaterThan(title!.x + title!.width);
  expect(face!.x + face!.width).toBeLessThanOrEqual(status!.x);
  await mood.click();
  const dialog = page.getByRole('dialog', { name: 'How are you feeling today?' });
  const slider = dialog.getByRole('slider', { name: 'Mood' });
  await expect(slider).toBeFocused();
  await slider.press('Home');
  await expect(slider).toHaveAttribute('aria-valuetext', 'Unhappy (1)');
  await slider.press('ArrowRight');
  await expect(slider).toHaveAttribute('aria-valuetext', 'Neutral (2)');
  await slider.press('ArrowRight');
  await expect(slider).toHaveAttribute('aria-valuetext', 'Happy (3)');
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0);
  await expect(mood).toBeFocused();
  await expect(mood).toHaveAccessibleName(/Not recorded/);
  await mood.click();
  await slider.press('End');
  await dialog.getByRole('button', { name: 'Submit mood' }).click();
  await expect(mood).toHaveAccessibleName(/Alex Morgan: Happy/);
  await page.getByRole('combobox', { name: 'Selected crew' }).selectOption('DEMO-CREW-002');
  const other = page.getByRole('button', { name: /^Mood for Jordan Lee:/ });
  await expect(other).toHaveAccessibleName(/Not recorded/);
  await other.click();
  await slider.press('Home');
  await dialog.getByRole('button', { name: 'Submit mood' }).click();
  await expect(other).toHaveAccessibleName(/Jordan Lee: Unhappy/);
  await page.reload();
  await expect(other).toHaveAccessibleName(/Jordan Lee: Unhappy/);
  await page.getByRole('combobox', { name: 'Selected crew' }).selectOption('DEMO-CREW-001');
  await expect(mood).toHaveAccessibleName(/Alex Morgan: Happy/);
  await expect(page.locator('.metric-card .status').filter({ hasText: /^LIVE$/ })).toHaveCount(6);
  await mkdir('../artifacts/screenshots', { recursive: true });
  await page.screenshot({ path: '../artifacts/screenshots/mood-dashboard.png' });
  await mood.click();
  await page.screenshot({ path: '../artifacts/screenshots/mood-dialog.png' });
  await dialog.getByRole('button', { name: 'Cancel' }).click();
  for (const width of [1920, 1024, 390]) {
    await page.setViewportSize({ width, height: 844 });
    await expect(mood).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)).toBe(false);
    await mood.click();
    const bounds = await dialog.boundingBox();
    expect(bounds!.x).toBeGreaterThanOrEqual(0);
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(width);
    await dialog.getByRole('button', { name: 'Cancel' }).click();
  }
});
