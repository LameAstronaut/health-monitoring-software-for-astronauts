import { test, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';

test('weekly plans stay per crew, can be rescheduled and cancelled, and complete after a saved examination', async ({ page, request }) => {
  const api = 'http://127.0.0.1:18000/api/v1';
  const control = await (await request.get(`${api}/demo/control`)).json();
  await request.post(`${api}/demo/control`, { data: { action: 'RESTART', expected_revision: control.revision, astronaut_id: 'DEMO-CREW-001' } });
  const now = (await (await request.get(`${api}/health`)).json()).server_time;
  const today = now.slice(0, 10);
  const next = new Date(now);
  next.setUTCDate(next.getUTCDate() + 7);
  const nextDay = next.toISOString().slice(0, 10);
  await page.goto('/');
  const calendar = page.getByRole('region', { name: 'Weekly examination calendar for Alex Morgan', exact: true });
  await expect(calendar.getByRole('button', { name: 'Schedule examination', exact: true })).toBeEnabled();
  await calendar.getByRole('button', { name: 'Schedule examination', exact: true }).click();
  const create = page.getByRole('dialog', { name: 'Schedule examination', exact: true });
  await create.getByRole('combobox', { name: 'Examination type' }).selectOption('BODY_TEMPERATURE');
  await create.getByLabel('Date and time (UTC)').fill(`${today}T10:30`);
  await create.getByRole('textbox', { name: 'Notes (optional)' }).fill('Crew A thermometer');
  await create.getByRole('button', { name: 'Save plan' }).click();
  const appointment = calendar.getByRole('listitem').filter({ hasText: 'Crew A thermometer' });
  await expect(appointment).toContainText('Body temperature');
  await expect(appointment).toContainText('10:30');
  await appointment.getByRole('button', { name: 'Reschedule', exact: true }).click();
  const edit = page.getByRole('dialog', { name: 'Reschedule examination', exact: true });
  await edit.getByLabel('Date and time (UTC)').fill(`${nextDay}T11:15`);
  await edit.getByRole('button', { name: 'Save changes' }).click();
  await expect(appointment).toHaveCount(0);
  await calendar.getByRole('button', { name: 'Next week', exact: true }).click();
  await expect(appointment).toContainText('11:15');
  await appointment.getByRole('button', { name: 'Cancel plan', exact: true }).click();
  await expect(appointment).toContainText('CANCELLED');
  await appointment.getByRole('button', { name: 'Reschedule', exact: true }).click();
  await edit.getByLabel('Date and time (UTC)').fill(`${today}T12:30`);
  await edit.getByRole('button', { name: 'Save changes' }).click();
  await calendar.getByRole('button', { name: 'This week', exact: true }).click();
  await expect(appointment).toContainText('12:30');
  await page.getByRole('combobox', { name: 'Selected crew' }).selectOption('DEMO-CREW-002');
  const other = page.getByRole('region', { name: 'Weekly examination calendar for Jordan Lee', exact: true });
  await expect(other.getByText('Crew A thermometer')).toHaveCount(0);
  await other.getByRole('button', { name: 'Schedule examination', exact: true }).click();
  await create.getByRole('combobox', { name: 'Examination type' }).selectOption('LAB_PANEL');
  await create.getByLabel('Date and time (UTC)').fill(`${today}T13:00`);
  await create.getByRole('textbox', { name: 'Notes (optional)' }).fill('Crew B labs');
  await create.getByRole('button', { name: 'Save plan' }).click();
  await expect(other.getByText('Crew B labs')).toBeVisible();
  await page.reload();
  await expect(other.getByText('Crew B labs')).toBeVisible();
  await page.getByRole('combobox', { name: 'Selected crew' }).selectOption('DEMO-CREW-001');
  await expect(appointment).toBeVisible();
  await expect(calendar.getByText('Crew B labs')).toHaveCount(0);
  await mkdir('../artifacts/screenshots', { recursive: true });
  await calendar.screenshot({ path: '../artifacts/screenshots/weekly-examination-calendar.png' });
  for (const width of [1920, 1024, 390]) {
    await page.setViewportSize({ width, height: 844 });
    await expect(calendar).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)).toBe(false);
  }
  await page.setViewportSize({ width: 1366, height: 768 });
  await expect(appointment.getByRole('button', { name: 'Start examination', exact: true })).toBeEnabled();
  await appointment.getByRole('button', { name: 'Start examination', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Examinations', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Review & save result', exact: true })).toBeVisible();
  await expect(page.getByRole('cell', { name: '36.6 °C', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Review & save result', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Export synthetic report' })).toBeVisible();
  await page.getByRole('button', { name: 'Mission dashboard', exact: true }).click();
  await expect(appointment).toContainText('COMPLETED');
  await expect(appointment.getByRole('button', { name: 'Start examination', exact: true })).toHaveCount(0);
});
